def generated(root: Path) -> tuple[str, str]:
    return (root / "docs/REPORT.md").read_text(), (root / "README.md").read_text()


def assert_plain(text: str) -> None:
    assert not PLACEHOLDER_RE.search(text), PLACEHOLDER_RE.search(text)
    assert "\u2014" not in text
    assert not any(word in text.lower() for word in HYPE)


def test_full_synthetic_repo_passes_claimcheck_and_freshness(full_repo: Path) -> None:
    shim = make_shim(full_repo)
    log = report.generate(full_repo, module=shim)
    assert log[-1].startswith("REPORT: wrote 5 figure(s)")
    text, readme = generated(full_repo)
    assert_plain(text)
    assert_plain(readme)
    assert "Hand-written text stays as it is." in text
    for section in ("5.1", "5.2", "5.3", "5.4", "5.5", "5.6", "5.7", "5.8"):
        assert f"### {section} " in text
    assert text.count(report.SYNTHETIC_NOTE) >= 5  # pilot, E1, E2, E3, E4
    assert "Status: confirmatory, preregistered in `prereg/0001-e1.md`." in text
    assert "Status: exploratory (not preregistered)." in text  # pilot and E2
    assert "Holm p" in text and "Tokens per session" in text and "halflife-guard took" in text
    assert "Status: synthetic." in text and "(pilot)" in text
    plain_text = claimcheck.strip_markers(text)
    assert "| syn-a | 3 | 3 | 9 | 6 | qualifies |" in plain_text
    assert "| syn-b | 3 | 2 | 6 | 4 | does not qualify |" in plain_text
    assert "`artifacts/pilot/family_choice.json`" in text and "it names syn-a." in text
    assert "confidence interval" in readme and "docs/figures/e1-hazard.svg" in readme
    for figure in re.findall(r"!\[[^\]]*\]\(([^)]+)\)", text):
        root = ET.parse(full_repo / "docs" / figure).getroot()
        assert root.find("{http://www.w3.org/2000/svg}title") is not None
        assert "Synthetic data" in (full_repo / "docs" / figure).read_text()
    checked = claimcheck.check(full_repo)
    assert checked.problems == 0, [line for line in checked.lines if line.startswith("FAIL")]
    assert checked.lines[-1].startswith("CLAIMCHECK: PASS")
    fresh = freshness.check(full_repo)
    assert fresh.problems == 0, [line for line in fresh.lines if line.startswith("FAIL")]
    assert re.match(r"FRESHNESS: PASS 1\d derivation\(s\)", fresh.lines[-1])
    before = {p: p.read_bytes() for p in sorted(full_repo.rglob("*")) if p.is_file()}
    report.generate(full_repo, module=shim)
    after = {p: p.read_bytes() for p in sorted(full_repo.rglob("*")) if p.is_file()}
    assert before == after  # deterministic: a second run changes nothing


