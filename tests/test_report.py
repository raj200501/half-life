def test_edge_cases_render_plainly(tmp_path: Path) -> None:
    """Synthetic edge cases: a failed G5 threshold, a negative interval, and missing parts."""
    cases = [{"kind": "cp", "label": True, "predicted": False}]
    detectors = {
        "precision": {"value": 0.9, "lo": 0.8, "hi": 0.95},
        "recall": {"value": 0.97, "lo": 0.93, "hi": 0.99},
        "cases": cases,
        "by_detector": {},
    }
    write_json(tmp_path, "artifacts/e0/detector_validation.json", detectors)
    store = report.Store(tmp_path)
    b = report.Build(store, report.Ledger(store))
    text = plain(report.detectors_text(b))
    assert "it is not met for precision" in text and "(0 of 1 detected)" in text
    detectors["precision"] = {"value": 0.96, "lo": 0.93, "hi": 0.99}
    write_json(tmp_path, "artifacts/e0/detector_validation.json", detectors)
    store = report.Store(tmp_path)
    b = report.Build(store, report.Ledger(store))
    text = plain(report.detectors_text(b))
    assert "both values meet it, but the lower interval bound of precision and recall" in text
    at = report.At("artifacts/e0/detector_validation.json")
    write_json(tmp_path, "artifacts/e0/detector_validation.json", {"d": {"lo": -0.2, "hi": -0.1}})
