def test_ledger_refuses_inconsistent_claims(tmp_path: Path) -> None:
    write_json(tmp_path, "artifacts/e0/detector_validation.json", {"a": 0.5, "b": True, "c": None})
    store = report.Store(tmp_path)
    led = report.Ledger(store)
    at = report.At("artifacts/e0/detector_validation.json")
    assert led.num("x.a", at, "/a", ".2f") == "<!-- claim:x.a -->0.50<!-- /claim -->"
    assert led.num("x.a", at, "/a", ".2f").endswith("0.50<!-- /claim -->")  # same spec reused
    assert led.num("x.c", at, "/c", ".2f") == report.NOT_ESTIMABLE
    assert led.peek(at, "/missing") is None
    with pytest.raises(report.ReportError, match="two different values"):
        led.num("x.a", at, "/a", ".3f")
    with pytest.raises(report.ReportError, match="does not match"):
        led.num("bad id", at, "/a", ".2f")
    with pytest.raises(report.ReportError, match="not a number or string"):
        led.num("x.b", at, "/b", "")
    with pytest.raises(report.ReportError, match="no key"):
        led.select(at, "/missing")
    with pytest.raises(report.ReportError, match="must hold"):
        led.allowed("95", "95", "no words")
    led.allowed("95", "95% interval", "level")
    led.allowed("95", "95% interval", "level")
    led.allowed("95", "95% interval", "other")
    assert led.allowlist[("95", "95% interval")] == ["level", "other"]
    write_json(tmp_path, "artifacts/other/thing.json", {"a": 1})
    with pytest.raises(report.ReportError, match="no derivation or raw declaration"):
        led.num("x.other", report.At("artifacts/other/thing.json"), "/a", "d")
    (tmp_path / "artifacts/e0/broken.json").write_text("{")
    with pytest.raises(report.ReportError, match="not valid JSON"):
        store.load("artifacts/e0/broken.json")
    with pytest.raises(report.ReportError, match="not a list of rows"):
        store.rows("artifacts/e0/detector_validation.json")
    write_json(tmp_path, "artifacts/e0/list.json", [1])
    with pytest.raises(report.ReportError, match="not a JSON object"):
        store.obj("artifacts/e0/list.json")


