    assert checked.lines[-1].startswith("CLAIMCHECK: PASS")
    fresh = freshness.check(full_repo)
    assert fresh.problems == 0, [line for line in fresh.lines if line.startswith("FAIL")]
    assert re.match(r"FRESHNESS: PASS 1\d derivation\(s\)", fresh.lines[-1])
    before = {p: p.read_bytes() for p in sorted(full_repo.rglob("*")) if p.is_file()}
    report.generate(full_repo, module=shim)
    after = {p: p.read_bytes() for p in sorted(full_repo.rglob("*")) if p.is_file()}
