    assert led.peek(at, "/d") is not None
    assert report.reading(led, at, "/d", "up", "down") == "interval below zero: down"
    assert report.reading(led, at, "/missing", "up", "down") == "interval not estimable"
    rendered = report.estimate(led, "z", at, "/d", "value", ".1f")
    assert claimcheck.strip_markers(rendered) == "not estimable [-0.2, -0.1]"


