def git_init(root: Path) -> None:
    subprocess.run(["git", "init", "-q", str(root)], check=True, capture_output=True)


def make_shim(root: Path) -> str:
    """A module inside ``root`` that wraps the derivations, so freshness accepts their source."""
    name = f"shim_{uuid.uuid4().hex}"
    body = ['"""Derivation wrappers for a synthetic test repository."""', ""]
    body.append("from halflife import derive as _derive")
    for function in SHIM_FUNCTIONS:
        body += [
            "",
            "",
            f"def {function}(inputs, **params):",
            f"    return _derive.{function}(inputs, **params)",
        ]
    (root / f"{name}.py").write_text("\n".join(body) + "\n", encoding="utf-8")
    return name


def base_repo(root: Path, *, readme: str = README_TEXT) -> None:
    git_init(root)
    (root / "docs").mkdir(parents=True)
    (root / "docs/REPORT.md").write_text(REPORT_TEXT, encoding="utf-8")
    (root / "README.md").write_text(readme, encoding="utf-8")


def copy_real_e0_and_bench(root: Path) -> None:
    for rel in (
        "artifacts/e0/detector_validation.json",
        "artifacts/e0/probe_scoring.json",
        "artifacts/bench/manifest.json",
    ):
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(REAL / rel, root / rel)
    shutil.copytree(REAL / "artifacts/bench/routes", root / "artifacts/bench/routes")


def bank_experiment(
    root: Path,
    kind: str,
    rows: tuple[list[dict[str, Any]], list[dict[str, Any]]],
    prereg: str | None,
) -> None:
    directory = root / "artifacts" / kind
    write_rows(directory / "sessions.jsonl", rows[0])
    write_rows(directory / "opportunities.jsonl", rows[1])
    provenance(directory, kind, prereg)


