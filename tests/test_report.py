def test_hand_written_manifest_entries_are_kept(tmp_path: Path) -> None:
    base_repo(tmp_path)
    copy_real_e0_and_bench(tmp_path)
    manual = {
        "schema": report.SCHEMA,
        "documents": ["docs/OTHER.md"],
        "claims": {
            "manual.cases": {
                "artifact": "artifacts/e0/detector_validation.json",
                "pointer": "/cases",
                "aggregate": "count",
                "format": "d",
            },
            "old.generated": {
                "artifact": "artifacts/e0/detector_validation.json",
                "field": "/precision/value",
                "format": ".3f",
                "note": report.GENERATED,
            },
        },
        "allowlist": [
            {"value": "3", "context": "within 3 minutes", "reason": "G4 limit"},
            {"value": "7", "context": "stale 7 entry", "reason": "old" + report.TAG},
        ],
        "derivations": {},
        "raw": {
            "artifacts/e2/sessions.jsonl": "kept by hand",
            "artifacts/x.json": "old" + report.TAG,
        },
    }
    (tmp_path / "artifacts/claims.json").write_text(json.dumps(manual))
    (tmp_path / "docs/OTHER.md").write_text("Other document.\n")
    report.generate(tmp_path)
    manifest = json.loads((tmp_path / "artifacts/claims.json").read_text())
    assert "manual.cases" in manifest["claims"] and "old.generated" not in manifest["claims"]
    assert manifest["documents"] == ["docs/OTHER.md"]
    contexts = [entry["context"] for entry in manifest["allowlist"]]
    assert "within 3 minutes" in contexts and "stale 7 entry" not in contexts
    assert manifest["raw"]["artifacts/e2/sessions.jsonl"] == "kept by hand"
    assert "artifacts/x.json" not in manifest["raw"]
    assert manifest["raw"]["artifacts/e0/detector_validation.json"].endswith(report.TAG)
    (tmp_path / "artifacts/claims.json").write_text("[1, 2]")
    with pytest.raises(report.ReportError, match="not a JSON object"):
        report.generate(tmp_path)
    (tmp_path / "artifacts/claims.json").write_text("{")
    with pytest.raises(report.ReportError, match="not valid JSON"):
        report.generate(tmp_path)
    bad = manual | {"claims": {"bad id!": {"artifact": "artifacts/e0/detector_validation.json"}}}
    (tmp_path / "artifacts/claims.json").write_text(json.dumps(bad))
    with pytest.raises(report.ReportError, match="would not validate"):
        report.generate(tmp_path)


