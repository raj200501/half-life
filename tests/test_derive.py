def test_e1_outputs_equal_the_analysis_and_share_one_run(monkeypatch: pytest.MonkeyPatch) -> None:
    sessions, opportunities = synthetic_e1()
    inputs = {
        "artifacts/e1/sessions.jsonl": sessions,
        "artifacts/e1/opportunities.jsonl": opportunities,
    }
    expected = as_json(e1_analysis.analyze(sessions, opportunities, FAST))
    calls: list[int] = []
    original = derive.ANALYSES["e1"]

    def counting(*args: Any) -> dict[str, dict[str, Any]]:
        calls.append(1)
        return original(*args)

    monkeypatch.setitem(derive.ANALYSES, "e1", counting)
    monkeypatch.setattr(derive, "_CACHE", {})
    for stem in derive.E1_OUTPUTS:
        produced = derive.e1_output(inputs, output=stem, n_boot=20, seed=3)
        assert as_json(produced) == expected[stem]
        produced.clear()  # a caller changing its copy leaves the cached result intact
    assert len(calls) == 1
    assert (
        as_json(derive.e1_output(inputs, output="hazard", n_boot=20, seed=3)) == expected["hazard"]
    )
    with pytest.raises(derive.DeriveError, match="no output"):
        derive.e1_output(inputs, output="nope", n_boot=20, seed=3)


def test_cache_is_bounded(monkeypatch: pytest.MonkeyPatch) -> None:
    sessions, opportunities = synthetic_e1(n_sessions=12)
    monkeypatch.setattr(derive, "_CACHE", {})
    monkeypatch.setattr(derive, "_CACHE_SIZE", 1)
    inputs = {"x/sessions.jsonl": sessions, "x/opportunities.jsonl": opportunities}
    derive.e1_output(inputs, output="km", n_boot=5, seed=1)
    derive.e1_output(inputs, output="km", n_boot=5, seed=2)
    assert len(derive._CACHE) == 1


def test_arm_outputs_equal_arms_analysis() -> None:
    for kind, arms, function, outputs in (
        ("e3", E3_ARMS, derive.e3_output, derive.E3_OUTPUTS),
        ("e4", E4_ARMS, derive.e4_output, derive.E4_OUTPUTS),
    ):
        sessions, opportunities = synthetic_arms(kind, arms)
        inputs = {
            f"a/{kind}/sessions.jsonl": sessions,
            f"a/{kind}/opportunities.jsonl": opportunities,
        }
        expected = as_json(derive.ANALYSES[kind](sessions, opportunities, FAST))
        for stem in outputs:
            assert as_json(function(inputs, output=stem, n_boot=20, seed=3)) == expected[stem]
    sessions, opportunities = synthetic_arms(
        "e2", [{}], families=("haiku", "sonnet"), model_key="model"
    )
    inputs = {"a/e2/sessions.jsonl": sessions, "a/e2/opportunities.jsonl": opportunities}
    expected = as_json(arms_analysis.analyze_e2(sessions, opportunities, FAST))
    for stem in derive.E2_OUTPUTS:
        assert as_json(derive.e2_output(inputs, output=stem, n_boot=20, seed=3)) == expected[stem]


def test_settings_params_reads_and_checks_recorded_settings() -> None:
    content = {"settings": {"n_boot": 20, "seed": 3, "max_position": 150, "level": 0.95}}
    assert derive.settings_params(content, "x") == content["settings"]
    with pytest.raises(derive.DeriveError, match="records no analysis settings"):
        derive.settings_params({}, "x")
    bad = {"settings": content["settings"] | {"n_boot": True}}
    with pytest.raises(derive.DeriveError, match="n_boot"):
        derive.settings_params(bad, "x")


