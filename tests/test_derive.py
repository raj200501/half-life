def synthetic_e1(
    n_sessions: int = 24, seed: int = 7, families: Sequence[str] = ("syn-a", "syn-b")
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Synthetic E1 sessions and opportunities from a known hazard model (not model data)."""
    rng = random.Random(seed)
    sessions: list[dict[str, Any]] = []
    opportunities: list[dict[str, Any]] = []
    for family in families:
        for i in range(n_sessions):
            sid = f"syn-e1-{i}"
            strategy = "full_summary" if i % 2 else "sham"
            sessions.append(
                {
                    "session_id": sid,
                    "run_id": f"syn-run-{family}",
                    "family": family,
                    "model": f"{family}-model",
                    "template_id": "syn-template",
                    "confirmatory": True,
                    "synthetic": True,
                    "reached_first_dp": i % 11 != 0,
                }
            )
            if i % 11 == 0:
                continue
            position = 0
            for j in range(4):
                position += rng.randint(5, 30)
                count = min(3, position // 40)
                eta = -2.5 + 0.4 * math.log1p(position) + (0.5 * count if i % 2 else 0.0)
                opportunities.append(
                    {
                        "session_id": sid,
                        "family": family,
                        "position": position,
                        "compaction_count": count,
                        "constraint_type": TYPES[(i + j) % 4],
                        "strategy": strategy,
                        "violated": rng.random() < 1 / (1 + math.exp(-eta)),
                        "acted": rng.random() < 0.8,
                        "recalled_before": rng.random() < 0.6,
                        "span_calls": 3,
                        "synthetic": True,
                    }
                )
    return sessions, opportunities


def synthetic_arms(
    arm_key: str,
    arms: Sequence[Mapping[str, str]],
    families: Sequence[str] = ("syn-a",),
    per_arm: int = 4,
    seed: int = 2,
    model_key: str = "family",
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Synthetic E2, E3, or E4 rows; the arm index raises the violation chance (not model data).

    ``model_key="model"`` makes ``families`` model tiers, as E2 rows carry them.
    """
    rng = random.Random(seed)
    sessions: list[dict[str, Any]] = []
    opportunities: list[dict[str, Any]] = []
    for family in families:
        for a, arm in enumerate(arms):
            for i in range(per_arm):
                sid = f"syn-{arm_key}-{a}-{i}"
                ident = (
                    {"family": family, "model": f"{family}-model"}
                    if model_key == "family"
                    else {"family": "claude", "model": family}
                )
                sessions.append(
                    {
                        "session_id": sid,
                        **ident,
                        "template_id": f"syn-tpl-{i % 3}",
                        "confirmatory": True,
                        "synthetic": True,
                        "reached_first_dp": True,
                        "mitigation": arm.get("mitigation", "none"),
                        "subtasks_checked": 4,
                        "subtasks_succeeded": 3 if a % 2 else 4,
                        "usage": {
                            "step": {
                                "calls": 10,
                                "prompt_tokens": 1000 + 100 * a,
                                "completion_tokens": 50,
                                "elapsed_s": 20.0 + a,
                            },
                        },
                    }
                )
                for j in range(4):
                    row = {
                        "session_id": sid,
                        **ident,
                        "constraint_type": TYPES[j],
                        "position": 5 + 10 * j + i % 5,
                        "compaction_count": rng.randint(0, 2),
                        "violated": rng.random() < 0.15 + 0.1 * a,
                        "recalled_before": rng.random() < 0.6,
                        "span_calls": 2,
                        "placement": "first_user",
                        "phrasing": "bare",
                        "strategy": "full_summary",
                        "mitigation": "none",
                        "synthetic": True,
                    } | dict(arm)
                    opportunities.append(row)
    return sessions, opportunities


E3_ARMS = [
    {"placement": p, "phrasing": ph}
    for p in ("first_user", "system", "pinned_file", "reminder")
    for ph in ("bare", "reason")
]
E4_ARMS = [{"mitigation": m} for m in ("none", *arms_analysis.MITIGATIONS)]


def pilot_templates() -> list[bench.LoadedTemplate]:
    """The real pilot-split templates, so compaction logs can name their real constraint ids."""
    return [t for t in bench.load_all() if t.template.split == "pilot"]


def synthetic_pilot(
    root: Path, directory: str = "artifacts/pilot", families: Sequence[str] = ("syn-a", "syn-b")
) -> None:
    """A synthetic banked pilot under ``root``: rows, compaction logs, and provenance.

    Every family runs one session per pilot template; ``syn-b`` misses its first decision
    point, so it reaches the first decision point in fewer sessions than ``syn-a``.
    """
    templates = pilot_templates()
    out = root / directory
    sessions, opportunities, events = [], [], []
    for f_index, family in enumerate(families):
        run_id = f"syn-pilot-{family}"
        for i, template in enumerate(templates):
            ids = [c.id for c in template.template.constraints]
            sid = f"syn-pilot-{i}"
            reached = not (f_index == 1 and i == 0)
            sessions.append(
                {
                    "session_id": sid,
                    "run_id": run_id,
                    "family": family,
                    "model": f"{family}-model",
                    "template_id": template.id,
                    "confirmatory": False,
                    "synthetic": True,
                    "reached_first_dp": reached,
                    "dps_reached": 3 if reached else 0,
                    "n_tool_calls": 60 + 10 * i,
                    "n_compactions": 2,
                    "probe_leaks": [],
                }
            )
            for j in range(3 if reached else 0):
                opportunities.append(
                    {
                        "session_id": sid,
                        "run_id": run_id,
                        "family": family,
                        "violated": (i + j) % 3 == 0,
                        "acted": j != 1,
                        "synthetic": True,
                    }
                )
            event_id = f"c{i}"
            rel = f"{directory}/compactions/{run_id}/{sid}/{event_id}.json"
            log = {
                "event_id": event_id,
                "strategy": "full_summary",
                "tool_call_index": 10 + i,
                "scheduled": True,
                "tokens_before": 3000,
                "tokens_after": 900,
                "before": [{"role": "system", "content": "synthetic"}],
                "after": [{"role": "system", "content": "synthetic"}],
                "summary": "synthetic summary" if i != 2 or f_index else "",
                "constraint_text_retained": dict.fromkeys(ids, True),
            }
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(log), encoding="utf-8")
            events.append(
                {
                    "run_id": run_id,
                    "session_id": sid,
                    "event_id": event_id,
                    "strategy": "full_summary",
                    "tool_call_index": 10 + i,
                    "tokens_before": 3000,
                    "tokens_after": 900,
                    "log_path": rel,
                    "log_sha256": "0" * 64,
                }
            )
    write_rows(out / "sessions.jsonl", sessions)
    write_rows(out / "opportunities.jsonl", opportunities)
    (out / "compaction_logs.json").write_text(json.dumps({"events": events}), encoding="utf-8")
    provenance(out, "pilot", None)


def write_rows(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in rows), encoding="utf-8")


def provenance(directory: Path, experiment_name: str, prereg: str | None) -> None:
    """A provenance.json like ``bank_runs`` writes, flagged synthetic."""
    record = {
        "experiment": experiment_name,
        "prereg": prereg,
        "confirmatory": prereg is not None,
        "synthetic": True,
        "git_sha": SHA,
        "command": "synthetic test fixture (tests/test_derive.py)",
    }
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "provenance.json").write_text(json.dumps(record), encoding="utf-8")


def load_dir(root: Path, directory: str) -> dict[str, Any]:
    """A directory input as freshness loads it: each .json/.jsonl file to its content."""
    return {
        path.relative_to(root).as_posix(): load_artifact(path)
        for path in sorted((root / directory).rglob("*"))
        if path.suffix in {".json", ".jsonl"}
    }


def as_json(value: Any) -> Any:
    return json.loads(json.dumps(value))


# --------------------------------------------------------------------------- bench and E0


def real_routes() -> dict[str, Any]:
    return {"artifacts/bench/routes/": load_dir(ROOT, "artifacts/bench/routes")}


def test_bench_manifest_rederives_the_banked_manifest() -> None:
    banked = load_artifact(ROOT / "artifacts/bench/manifest.json")
    assert as_json(derive.bench_manifest(real_routes())) == banked


def test_bench_manifest_refuses_stale_or_missing_routes() -> None:
    inputs = real_routes()
    routes = dict(inputs["artifacts/bench/routes/"])
    first = sorted(routes)[0]
    stale = dict(routes) | {first: dict(routes[first]) | {"template_sha256": "f" * 64}}
    with pytest.raises(derive.DeriveError, match="another version"):
        derive.bench_manifest({"artifacts/bench/routes/": stale})
    missing = {k: v for k, v in routes.items() if k != first}
    with pytest.raises(derive.DeriveError, match="no banked compliant route"):
        derive.bench_manifest({"artifacts/bench/routes/": missing})
    with pytest.raises(derive.DeriveError, match="missing"):
        derive.bench_manifest({})


def test_probe_scoring_rederives_the_banked_agreement() -> None:
    banked = load_artifact(ROOT / "artifacts/e0/probe_scoring.json")
    manifest = load_artifact(ROOT / "artifacts/bench/manifest.json")
    inputs = {"artifacts/bench/manifest.json": manifest}
    derived = as_json(derive.probe_scoring(inputs, answers=banked["answers"]))
    for pointer in derive.PROBE_SCORING_COMPARE:
        key = pointer.lstrip("/")
        assert derived[key] == banked[key], key


def test_probe_scoring_refuses_changed_templates_and_bad_paths() -> None:
    manifest = load_artifact(ROOT / "artifacts/bench/manifest.json")
    changed = dict(manifest)
    changed["templates"] = [dict(manifest["templates"][0]) | {"sha256": "e" * 64}]
    changed["templates"] += manifest["templates"][1:]
    answers = "src/halflife/data/probe_answers.yaml"
    with pytest.raises(derive.DeriveError, match="differ from the banked manifest"):
        derive.probe_scoring({"artifacts/bench/manifest.json": changed}, answers=answers)
    with pytest.raises(derive.DeriveError, match="no templates"):
        derive.probe_scoring({"artifacts/bench/manifest.json": {}}, answers=answers)
    with pytest.raises(derive.DeriveError, match="normal form"):
        derive.probe_scoring({"artifacts/bench/manifest.json": manifest}, answers="src/../x")
    with pytest.raises(derive.DeriveError, match="exactly one input"):
        derive.probe_scoring({}, answers=answers)


def test_e0_derivations_equal_what_e0_validation_writes(tmp_path: Path) -> None:
    synthetic_pilot(tmp_path)
    ids = {t.id: [c.id for c in t.template.constraints] for t in bench.load_all()}
    summary = experiment.e0_validation(
        tmp_path / "artifacts/pilot", tmp_path / "artifacts/e0", tmp_path, ids
    )
    assert summary["incomplete"] == 1  # the synthetic log with an empty summary
    source = "artifacts/pilot"
    inputs = {
        f"{source}/sessions.jsonl": load_artifact(tmp_path / source / "sessions.jsonl"),
        f"{source}/compaction_logs.json": load_artifact(tmp_path / source / "compaction_logs.json"),
        f"{source}/compactions/": load_dir(tmp_path, f"{source}/compactions"),
    }
    leakage = load_artifact(tmp_path / "artifacts/e0/probe_leakage.json")
    logs = load_artifact(tmp_path / "artifacts/e0/compaction_logs.json")
    assert as_json(derive.e0_probe_leakage(inputs, source=source)) == leakage
    assert as_json(derive.e0_compaction_logs(inputs, source=source)) == logs
    with pytest.raises(derive.DeriveError, match="not among the inputs"):
        derive.e0_compaction_logs(inputs | {f"{source}/compactions/": {}}, source=source)
    with pytest.raises(derive.DeriveError, match="no events list"):
        derive.e0_compaction_logs(inputs | {f"{source}/compaction_logs.json": []}, source=source)
    with pytest.raises(derive.DeriveError, match="not a list of rows"):
        derive.e0_probe_leakage({}, source=source)


def test_power_matches_the_power_command(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    synthetic_pilot(tmp_path)
    monkeypatch.chdir(tmp_path)
    out = "artifacts/power/e1.json"
    args = ["--pilot", "artifacts/pilot", "--out", out, "--n-sim", "2", "--seed", "5"]
    assert power.main(args) == 0
    banked = load_artifact(tmp_path / out)
    inputs = {
        "artifacts/pilot/sessions.jsonl": load_artifact(
            tmp_path / "artifacts/pilot/sessions.jsonl"
        ),
        "artifacts/pilot/opportunities.jsonl": load_artifact(
            tmp_path / "artifacts/pilot/opportunities.jsonl"
        ),
    }
    derived = as_json(derive.power_e1(inputs, n_sim=2, seed=5))
    for key in ("synthetic", "pilot", "grid"):
        assert derived[key] == banked[key], key
    assert any(row["pilot_rate"] for row in banked["grid"])


