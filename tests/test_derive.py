def write_json(root: Path, rel: str, content: Any) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(content), encoding="utf-8")


def test_declare_names_every_input_down_to_raw_data(tmp_path: Path) -> None:
    settings = {"settings": {"n_boot": 20, "seed": 3, "max_position": 150, "level": 0.95}}
    write_json(tmp_path, "artifacts/e0/probe_scoring.json", {"answers": "a.yaml"})
    write_json(tmp_path, "artifacts/e0/probe_leakage.json", {"source": "artifacts/pilot"})
    write_json(tmp_path, "artifacts/e0/compaction_logs.json", {"source": "artifacts/pilot"})
    grid = [{"inputs": {"n_sim": 2, "seed": 5}}]
    write_json(tmp_path, "artifacts/power/e1.json", {"pilot_dir": "artifacts/pilot", "grid": grid})
    for kind, stems in (("e1", derive.E1_OUTPUTS), ("e2", derive.E2_OUTPUTS)):
        for stem in stems:
            write_json(tmp_path, f"artifacts/{kind}/{stem}.json", settings)
    write_json(tmp_path, "artifacts/e3/rates.json", settings)
    write_json(tmp_path, "artifacts/e4/costs.json", settings)

    scoring = derive.declare("artifacts/e0/probe_scoring.json", tmp_path, "shim")
    assert set(scoring.derivations) == {
        "artifacts/e0/probe_scoring.json",
        "artifacts/bench/manifest.json",
    }
    assert scoring.derivations["artifacts/e0/probe_scoring.json"]["derive"] == "shim:probe_scoring"
    assert set(scoring.raw) == {"artifacts/bench/routes/"}
    logs = derive.declare("artifacts/e0/compaction_logs.json", tmp_path)
    assert set(logs.raw) == {
        "artifacts/pilot/sessions.jsonl",
        "artifacts/pilot/compaction_logs.json",
        "artifacts/pilot/compactions/",
    }
    leakage = derive.declare("artifacts/e0/probe_leakage.json", tmp_path)
    assert leakage.derivations["artifacts/e0/probe_leakage.json"]["params"] == {
        "source": "artifacts/pilot"
    }
    power_entry = derive.declare("artifacts/power/e1.json", tmp_path).derivations[
        "artifacts/power/e1.json"
    ]
    assert power_entry["params"] == {"n_sim": 2, "seed": 5}
    hazard = derive.declare("artifacts/e1/hazard.json", tmp_path)
    entry = hazard.derivations["artifacts/e1/hazard.json"]
    assert entry["params"] == {"output": "hazard"} | settings["settings"]
    assert entry["derive"] == "halflife.derive:e1_output" and entry["compare"] == [""]
    assert set(hazard.raw) == {"artifacts/e1/sessions.jsonl", "artifacts/e1/opportunities.jsonl"}
    for rel, function in (
        ("artifacts/e2/rates.json", "e2_output"),
        ("artifacts/e3/rates.json", "e3_output"),
        ("artifacts/e4/costs.json", "e4_output"),
    ):
        assert derive.declare(rel, tmp_path).derivations[rel]["derive"].endswith(function)
    for rel in (
        "artifacts/e0/detector_validation.json",
        "artifacts/e4/overhead.json",
        "artifacts/e2/sessions.jsonl",
        "artifacts/pilot/compactions/",
    ):
        assert set(derive.declare(rel, tmp_path).raw) == {rel}


def test_declare_refuses_unknown_or_underspecified_artifacts(tmp_path: Path) -> None:
    with pytest.raises(derive.DeriveError, match="no derivation or raw declaration"):
        derive.declare("artifacts/other/thing.json", tmp_path)
    with pytest.raises(derive.DeriveError, match="cannot be read"):
        derive.declare("artifacts/e1/hazard.json", tmp_path)
    write_json(tmp_path, "artifacts/e0/probe_scoring.json", {})
    with pytest.raises(derive.DeriveError, match="answers file"):
        derive.declare("artifacts/e0/probe_scoring.json", tmp_path)
    for source in ("artifacts", "../elsewhere", None):
        write_json(tmp_path, "artifacts/e0/probe_leakage.json", {"source": source})
        with pytest.raises(derive.DeriveError):
            derive.declare("artifacts/e0/probe_leakage.json", tmp_path)
    write_json(tmp_path, "artifacts/power/e1.json", {"pilot_dir": "artifacts/pilot", "grid": []})
    with pytest.raises(derive.DeriveError, match="simulation size"):
        derive.declare("artifacts/power/e1.json", tmp_path)


def test_declarations_merge() -> None:
    a = derive.Declarations({"x": {"derive": "m:f"}}, {"y": "raw"})
    a.update(derive.Declarations({"z": {"derive": "m:g"}}, {"w": "raw"}))
    assert set(a.derivations) == {"x", "z"} and set(a.raw) == {"y", "w"}
